# ЗАДАНИЕ 11
import math

# радиус окружности
radius = 5.0 # значение с плавающей точкой 

# длина окружности: 2 * pi * r
circum = 2 * math.pi * radius # константа существующая в библеотеке математика

# площадь круга: pi * r^2
area = math.pi * radius ** 2

print(f"Радиус: {radius}")
print(f"Длина окружности: {circum:.2f}") # 2f это округление в большую сторону
print(f"Площадь круга: {area:.2f}")

# квадратный корень
number = 16
sqrt_result = math.sqrt(number) # функция квадратного корня
print(f"Квадратный корень из {number} = {sqrt_result}")



